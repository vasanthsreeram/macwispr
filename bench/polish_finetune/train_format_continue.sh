#!/usr/bin/env bash
# Continue-train formatting SFT from the existing course-correction fused checkpoint.
#
# Base model: fused Sotto + course LoRA (already has cleanup + self-corrections)
# New adapter: format skills (bullets / numbered / checklist)
# Then fuse → PolishModel for MacWispr LFM builds.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$ROOT/.." && pwd)"
# shellcheck disable=SC1091
source "$ROOT/.venv-polish/bin/activate"

BASE_MODEL="${BASE_MODEL:-$ROOT/polish_finetune/fused/sotto-lc-ft-clean-fused}"
DATA="${DATA:-$ROOT/polish_finetune/data/format_sft}"
ADAPTER="${ADAPTER:-$ROOT/polish_finetune/adapters/sotto-format-sft}"
FUSED_OUT="${FUSED_OUT:-$ROOT/polish_finetune/fused/sotto-format-sft-fused}"

# LoRA is the safe continue-train path on a fused specialist; use FINE_TUNE_TYPE=full to try full SFT.
FINE_TUNE_TYPE="${FINE_TUNE_TYPE:-lora}"
ITERS="${ITERS:-800}"
BATCH="${BATCH:-2}"
# Slightly lower LR when continuing from a strong checkpoint
LR="${LR:-5e-6}"
LAYERS="${LAYERS:--1}"   # all layers for more format capacity
MAX_SEQ="${MAX_SEQ:-768}"
LORA_RANK="${LORA_RANK:-16}"

if [[ ! -d "$BASE_MODEL" ]]; then
  echo "error: base fused model missing: $BASE_MODEL" >&2
  exit 1
fi

if [[ ! -f "$DATA/train.jsonl" ]]; then
  echo "==> Building format SFT dataset"
  python "$ROOT/polish_finetune/build_format_sft_data.py" --out "$DATA"
fi

mkdir -p "$(dirname "$ADAPTER")" "$FUSED_OUT"

echo "=== Continue-train (format) ==="
echo "base=$BASE_MODEL"
echo "data=$DATA"
echo "adapter=$ADAPTER"
echo "type=$FINE_TUNE_TYPE iters=$ITERS batch=$BATCH lr=$LR layers=$LAYERS"

START=$(date +%s)

# mlx_lm.lora accepts --fine-tune-type full|lora|dora
# Note: LoRA rank is configured via config or defaults; we pass num-layers -1 for all.
EXTRA=()
if [[ "$FINE_TUNE_TYPE" == "lora" || "$FINE_TUNE_TYPE" == "dora" ]]; then
  # Higher rank via a tiny config file if supported
  CFG="$ADAPTER/train_config.yaml"
  mkdir -p "$ADAPTER"
  cat >"$CFG" <<EOF
# generated by train_format_continue.sh
lora_parameters:
  rank: ${LORA_RANK}
  dropout: 0.0
  scale: 20.0
EOF
  EXTRA+=(-c "$CFG")
fi

mlx_lm.lora \
  --model "$BASE_MODEL" \
  --train \
  --data "$DATA" \
  --fine-tune-type "$FINE_TUNE_TYPE" \
  --batch-size "$BATCH" \
  --iters "$ITERS" \
  --learning-rate "$LR" \
  --num-layers "$LAYERS" \
  --max-seq-length "$MAX_SEQ" \
  --adapter-path "$ADAPTER" \
  --save-every 200 \
  --steps-per-eval 100 \
  --steps-per-report 20 \
  --seed 42 \
  "${EXTRA[@]}"

echo "==> Fusing adapter into standalone model → $FUSED_OUT"
rm -rf "$FUSED_OUT"
mlx_lm.fuse \
  --model "$BASE_MODEL" \
  --adapter-path "$ADAPTER" \
  --save-path "$FUSED_OUT"

END=$(date +%s)
echo "Wall time: $((END - START))s"
echo "Fused model ready: $FUSED_OUT"
echo "Point the app at it with:"
echo "  export MACWISPR_POLISH_MODEL=\"$FUSED_OUT\""
echo "or rebuild LFM branch with POLISH_MODEL_SRC=$FUSED_OUT"
